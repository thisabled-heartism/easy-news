// 날씨 관련 기사 감지 (오탐 방지를 위해 고정밀 키워드만 사용)
const WEATHER_PATTERNS: RegExp[] = [
  // 명확한 기상 용어
  /날씨/, /기상청/, /기상특보/, /기상예보/, /기상정보/,
  /강수확률/, /강수량/, /강우량/, /적설량/,
  /체감온도/, /최고기온/, /최저기온/, /평년기온/,

  // 기상 현상 (구체적인 표현만)
  /폭염/, /열대야/, /폭우/, /호우/, /폭설/, /폭풍/, /태풍/, /허리케인/,
  /한파/, /동장군/, /장마/, /장마전선/,
  /미세먼지/, /초미세먼지/, /황사/, /(?<![가-힣])안개(?![가-힣])/,
  /우박/, /진눈깨비/, /함박눈/, /빗줄기/, /비바람/,

  // 주의보·경보
  /호우주의보/, /호우경보/, /강풍주의보/, /강풍경보/,
  /한파주의보/, /한파경보/, /폭염주의보/, /폭염경보/,
  /건조주의보/, /대설주의보/, /태풍주의보/,

  // 비/눈은 동사 결합으로만
  /비가\s*내/, /비가\s*온/, /비가\s*올/, /비가\s*그/, /비를\s*뿌/, /비\s*그칠/,
  /눈이\s*내/, /눈이\s*온/, /눈이\s*올/, /눈\s*쌓/, /눈\s*그칠/,
  /(?<![가-힣])소나기(?![가-힣])/,

  // 하늘 상태
  /맑겠/, /흐리겠/, /흐릴\s*전망/, /개겠/, /구름\s*많/, /구름\s*가/,

  // 기온 표현
  /기온이\s*[\d영하떨오]/, /기온\s*[\d영하떨오]/, /영하\s*\d/, /영상\s*\d/,
  /낮\s*기온/, /아침\s*기온/, /낮\s*최고/, /낮\s*최저/
];

// 정확도 우선: 제목만 검사 (본문에 우연히 들어간 단어로 인한 오탐 방지)
export function isWeatherArticle(title: string, _body: string = ""): boolean {
  return WEATHER_PATTERNS.some(re => re.test(title));
}
